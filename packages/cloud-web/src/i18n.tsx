import { createContext, type ReactNode, useContext, useEffect, useMemo, useState } from 'react';
import { BRAND, displayText } from '@maka-cloud/client';
import { en, type Key, serverChoices, zhHans } from './strings';

export type Language = 'zh-Hans' | 'en';
export type LanguageChoice = 'system' | Language;
type Params = Record<string, string | number>;
export const LANGUAGE_KEY = 'maka.language';

export function languageFor(tags: readonly string[]): Language {
  const first = tags[0]?.toLowerCase() ?? '';
  return first === 'en' || first.startsWith('en-') ? 'en' : 'zh-Hans';
}

function systemLanguage(): Language {
  return languageFor(globalThis.navigator?.languages ?? []);
}

function savedChoice(): LanguageChoice {
  try {
    const stored = globalThis.localStorage?.getItem(LANGUAGE_KEY);
    return stored === 'en' || stored === 'zh-Hans' ? stored : 'system';
  } catch {
    return 'system';
  }
}

const choiceKeys = new Map(serverChoices.map(([id, label, key]) => [`${id}\n${label}`, key]));
const hasKey = (key: string): key is Key => Object.prototype.hasOwnProperty.call(zhHans, key);

export function translator(language: Language) {
  function t(key: Key, params?: Params): string {
    const template = (language === 'en' ? en[key] : zhHans[key]) ?? zhHans[key];
    return template.replace(/\{(\w+)\}/gu, (all, name: string) =>
      params?.[name] === undefined ? all : String(params[name]),
    );
  }

  /** Only for text generated by cloud-client presentation helpers, never agent/server prose. */
  function shared(text: string): string {
    if (language === 'en') return text;
    if (hasKey(text)) return t(text);
    const patterns: ReadonlyArray<readonly [RegExp, Key, readonly string[]]> = [
      [
        /^Could not complete the request \((\d+)\)\. Try again\.$/u,
        'Could not complete the request ({status}). Try again.',
        ['status'],
      ],
      [/^Result file: (.*)$/su, 'Result file: {name}', ['name']],
      [/^Pull request #(\d+)$/u, 'Pull request #{number}', ['number']],
      [/^in (\d+) min$/u, 'in {count} min', ['count']],
      [/^in (\d+) h$/u, 'in {count} h', ['count']],
      [/^in (\d+) days$/u, 'in {count} days', ['count']],
      [/^(\d+) min ago$/u, '{count} min ago', ['count']],
      [/^(\d+) h ago$/u, '{count} h ago', ['count']],
      [/^(\d+) days ago$/u, '{count} days ago', ['count']],
      [/^Every (\d+) day$/u, 'Every {count} day', ['count']],
      [/^Every (\d+) days$/u, 'Every {count} days', ['count']],
      [/^Every (\d+) h$/u, 'Every {count} h', ['count']],
      [/^Every (\d+) min$/u, 'Every {count} min', ['count']],
      [/^Up to (.*) a run, (.*) a day$/u, 'Up to {run} a run, {day} a day', ['run', 'day']],
      [/^Used (\d+) times$/u, 'Used {count} times', ['count']],
      [/^(Used .+), last (.+)$/u, '{uses}, last {time}', ['uses', 'time']],
      [/^Ends (.+)$/u, 'Ends {time}', ['time']],
      [/^Maka's confidence: (.+)\.$/su, "Maka's confidence: {confidence}.", ['confidence']],
      [
        /^Could not pause “(.*)”\. It keeps running\. (.*)$/su,
        'Could not pause “{title}”. It keeps running. {error}',
        ['title', 'error'],
      ],
      [
        /^Could not resume “(.*)”\. It stays paused\. (.*)$/su,
        'Could not resume “{title}”. It stays paused. {error}',
        ['title', 'error'],
      ],
    ];
    for (const [pattern, key, names] of patterns) {
      const match = pattern.exec(text);
      if (!match) continue;
      const params = Object.fromEntries(
        names.map((name, index) => {
          const value = match[index + 1] ?? '';
          return [
            name,
            ['uses', 'time', 'error', 'run', 'day'].includes(name) ? shared(value) : value,
          ];
        }),
      );
      return t(key, params);
    }
    // Device-group captions are generated by deliveryModel, not filenames or agent captions.
    if (/^(Desktop|Tablet|Phone)(?:, (?:tablet|phone))* and (?:tablet|phone)$/u.test(text)) {
      const names = text
        .toLowerCase()
        .split(/, | and /u)
        .map((name) => shared(name.charAt(0).toUpperCase() + name.slice(1)));
      return t('{items} and {last}', {
        items: names.slice(0, -1).join(t(', ')),
        last: names.at(-1) ?? '',
      });
    }
    return text;
  }

  return {
    language,
    t,
    shared,
    choiceLabel: (id: string, label: string): string => {
      const key = choiceKeys.get(`${id}\n${label}`);
      return key ? t(key) : displayText(label);
    },
  };
}

export type Translator = ReturnType<typeof translator>;
type LanguageContextValue = Translator & {
  languageChoice: LanguageChoice;
  setLanguage: (choice: LanguageChoice) => void;
};
const initialChoice = savedChoice();
const LanguageContext = createContext<LanguageContextValue>({
  ...translator(initialChoice === 'system' ? systemLanguage() : initialChoice),
  languageChoice: initialChoice,
  setLanguage: () => {},
});

export const useT = () => useContext(LanguageContext);

export function LanguageProvider({
  children,
  language,
}: {
  children: ReactNode;
  language?: Language;
}) {
  const [choice, setChoice] = useState<LanguageChoice>(savedChoice);
  const [system, setSystem] = useState(systemLanguage);
  useEffect(() => {
    const changed = () => setSystem(systemLanguage());
    const stored = (event: StorageEvent) => {
      if (event.key === LANGUAGE_KEY || event.key === null) setChoice(savedChoice());
    };
    window.addEventListener('languagechange', changed);
    window.addEventListener('storage', stored);
    return () => {
      window.removeEventListener('languagechange', changed);
      window.removeEventListener('storage', stored);
    };
  }, []);
  const active = language ?? (choice === 'system' ? system : choice);
  const value = useMemo<LanguageContextValue>(
    () => ({
      ...translator(active),
      languageChoice: choice,
      setLanguage: (next) => {
        setChoice(next);
        try {
          globalThis.localStorage?.setItem(LANGUAGE_KEY, next);
        } catch {
          // The choice still works for this visit when storage is blocked.
        }
      },
    }),
    [active, choice],
  );
  useEffect(() => {
    document.documentElement.lang = active;
    if ('serviceWorker' in navigator) {
      void navigator.serviceWorker
        .getRegistration('/sw.js')
        .then((registration) => {
          registration?.active?.postMessage({
            type: 'maka.language',
            language: choice === 'system' ? 'system' : active,
          });
        })
        .catch(() => {});
    }
    document.title = `${BRAND.name} — ${value.t(BRAND.tagline)}`;
  }, [active, value]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
